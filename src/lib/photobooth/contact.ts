const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

/** Mail du portrait : sujet, texte et HTML (image en piece jointe, cid « portrait »). */
export function portraitMail(o: { locale: string | undefined; title: string; campaign: string; shareLink: string | null }) {
  const loc: Locale = o.locale === "en" || o.locale === "ar" ? o.locale : "fr";
  const m = MAIL[loc];
  const dir = loc === "ar" ? "rtl" : "ltr";
  const subject = `${m.subject} · ${o.campaign}`;
  const text = [`${m.hello}${o.title ? ` : ${o.title}` : ""}.`, m.body, o.shareLink ? `${m.link} : ${o.shareLink}` : "", "", m.ai, m.why, "", "FMRXR// · fmrxr.com"]
    .filter((l, i, a) => l || a[i - 1]).join("\n");
  const html = `<div dir="${dir}" style="font-family:system-ui,sans-serif;max-width:560px;color:#111;font-size:15px;line-height:1.5">
<p style="font-size:11px;letter-spacing:.14em;text-transform:uppercase;color:#666;margin:0 0 12px">${esc(o.campaign)}</p>
<p style="font-size:22px;font-weight:800;margin:0 0 6px">${esc(m.hello)}</p>
${o.title ? `<p style="margin:0 0 16px;color:#444">${esc(o.title)}</p>` : ""}
<img src="cid:portrait" alt="" style="width:100%;border-radius:12px;display:block">
<p style="margin:16px 0 0">${esc(m.body)}</p>
${o.shareLink ? `<p><a href="${esc(o.shareLink)}" style="color:#111">${esc(m.link)}</a></p>` : ""}
<p style="font-size:12px;color:#666;border-top:1px solid #ddd;margin-top:20px;padding-top:12px">${esc(m.ai)}<br>${esc(m.why)}</p>
<p style="font-size:12px;color:#666">FMRXR<span style="color:#2c9a2c">//</span> · <a href="https://fmrxr.com" style="color:#666">fmrxr.com</a></p>
</div>`;
  return { subject, text, html };
}

/** Export CSV des contacts (UTF-8 avec BOM : Excel ouvre les accents). */
export function contactsCsv(rows: { date: string; title: string; contact: Contact }[]): string {
  const cell = (v: string) => (/[",\n;]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
  const head = ["date", "name", "email", "phone", "answer", "marketing_opt_in", "portrait"];
  const lines = rows.map(({ date, title, contact: c }) =>
    [date, c.name ?? "", c.email ?? "", c.phone ?? "", c.answer ?? "", c.optIn ? "yes" : "no", title].map(cell).join(","));
  return "﻿" + [head.join(","), ...lines].join("\r\n") + "\r\n";
}
