export type Contact = { name?: string; email?: string; phone?: string; answer?: string; optIn: boolean; at: string };
export type Delivery = { email: string; at: string; sentAt?: string | null; error?: string | null };

const EMAIL = /^[^\s@<>()"',;:\\]+@[^\s@<>()"',;:\\]+\.[a-z]{2,}$/i;
export const isEmail = (s: unknown): s is string => typeof s === "string" && s.length <= 200 && EMAIL.test(s.trim());

/** Telephone : chiffres, espaces, + ( ) - ; 6 a 20 chiffres. */
export function cleanPhone(s: unknown): string | null {
  if (typeof s !== "string") return null;
  const t = s.trim().replace(/[^\d+()\s-]/g, "");
  const digits = t.replace(/\D/g, "");
  return digits.length >= 6 && digits.length <= 20 ? t : null;
}

export const cleanText = (s: unknown, max: number) => (typeof s === "string" ? s.replace(/\s+/g, " ").trim().slice(0, max) : "");

export type ContactInput = { name?: unknown; email?: unknown; phone?: unknown; answer?: unknown; optIn?: unknown };

/**
 * Formulaire envoye par la borne, valide selon la campagne. Sans option
 * contact : l'email seul, pour recevoir le portrait.
 */
export function parseContact(input: ContactInput, config: CampaignConfig, now = new Date()):
  | { ok: true; contact: Contact | null; delivery: Delivery | null }
  | { ok: false; error: string } {
  const lead = config.leadCapture.enabled;
  const email = typeof input.email === "string" && input.email.trim() ? input.email.trim() : "";
  if (email && !isEmail(email)) return { ok: false, error: "INVALID_EMAIL" };
  const at = now.toISOString();
  if (!lead) {
    if (!config.emailDelivery || !email) return { ok: false, error: "INVALID_EMAIL" };
    return { ok: true, contact: null, delivery: { email, at, sentAt: null } };
  }
  const f = config.leadCapture.fields;
  const name = f.includes("name") ? cleanText(input.name, 120) : "";
  const phoneRaw = f.includes("phone") ? cleanText(input.phone, 40) : "";
  const phone = phoneRaw ? cleanPhone(phoneRaw) : null;
  if (phoneRaw && !phone) return { ok: false, error: "INVALID_PHONE" };
  if (f.includes("email") && !email) return { ok: false, error: "INVALID_EMAIL" };
  if (f.includes("name") && !name) return { ok: false, error: "MISSING_NAME" };
  if (!email && !phone) return { ok: false, error: "MISSING_CONTACT" };
  const answer = config.leadCapture.question ? cleanText(input.answer, 300) : "";
  const contact: Contact = {
    ...(name ? { name } : {}), ...(email ? { email } : {}), ...(phone ? { phone } : {}), ...(answer ? { answer } : {}),
    optIn: input.optIn === true || input.optIn === "true", at,
  };
  return { ok: true, contact, delivery: email && config.emailDelivery ? { email, at, sentAt: null } : null };
}

